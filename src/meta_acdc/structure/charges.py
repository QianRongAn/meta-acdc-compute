def unified_charges(resname: str, has_oxt: bool = False,
                    first_in_chain: bool = False) -> dict[str, float]:
    """United-atom heavy-atom charges for one residue instance.

    Returns {} when the residue type is unknown (callers skip such atoms).
    """
    key = ALIASES.get(resname.upper()[:3], resname.upper()[:3])
